#!/usr/bin/env node
/**
 * Reads all files from the template/ directory and generates
 * src/github/template-files.ts — a TypeScript module that exports
 * the file tree as a Record<string, string> (path → content).
 *
 * Run this script whenever template files change:
 *   node scripts/embed-template.mjs
 *
 * It is automatically run as part of `npm run build:ui`.
 */

import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "fs";
import { join, relative } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const TEMPLATE_DIR = join(__dirname, "..", "template");
const OUT_FILE = join(__dirname, "..", "src", "github", "template-files.ts");

/** Recursively collect all files under a directory */
function collectFiles(dir) {
	const entries = [];
	for (const name of readdirSync(dir)) {
		const full = join(dir, name);
		const stat = statSync(full);
		if (stat.isDirectory()) {
			entries.push(...collectFiles(full));
		} else {
			entries.push(full);
		}
	}
	return entries;
}

const files = collectFiles(TEMPLATE_DIR);

const entries = files.map((fullPath) => {
	const relPath = relative(TEMPLATE_DIR, fullPath).replace(/\\/g, "/");
	const content = readFileSync(fullPath, "utf-8");
	return [relPath, content];
});

// Generate TypeScript source
const lines = [
	"// AUTO-GENERATED by scripts/embed-template.mjs — do not edit by hand",
	"// Run `node scripts/embed-template.mjs` or `npm run build:ui` to regenerate.",
	"",
	"/** All template files, keyed by their path relative to the repo root. */",
	"export const TEMPLATE_FILES: Record<string, string> = {",
];

for (const [path, content] of entries) {
	// Use JSON.stringify for safe escaping of the content string
	lines.push(`\t${JSON.stringify(path)}: ${JSON.stringify(content)},`);
}

lines.push("};");
lines.push("");

mkdirSync(join(__dirname, "..", "src", "github"), { recursive: true });
writeFileSync(OUT_FILE, lines.join("\n"), "utf-8");

console.log(`✓ Embedded ${entries.length} template files → ${OUT_FILE}`);
